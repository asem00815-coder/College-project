function draw() {
	const {scale, ox, oy} = transform;
	ctx.clearRect(0, 0, canvas.width, canvas.height);
	ctx.fillStyle = COLOR_BG;
	ctx.fillRect(0, 0, canvas.width, canvas.height);

	for (let i = 0; i < REGIONS.length; i++) {
		const {pts} = REGIONS[i];
		if (pts.length < 3) continue;

		ctx.beginPath();
		ctx.moveTo(pts[0].x * scale + ox, pts[0].y * scale + oy);
		for (let j = 1; j < pts.length; j++) {ctx.lineTo(pts[j].x * scale + ox, pts[j].y * scale + oy)}
		ctx.closePath();

		const isHovered = i === hoverIndex;
		ctx.fillStyle = isHovered ? COLOR_FILL_HOVER : COLOR_FILL;
		ctx.strokeStyle = isHovered ? COLOR_STROKE_HOVER : COLOR_STROKE;
		ctx.lineWidth = isHovered ? 2 : 0.8;
		ctx.fill();
		ctx.stroke();
	}
}

function resize() {
	const w = canvas.parentElement.clientWidth;
	const scale = w / MAP_W;
	canvas.width = w;
	canvas.height = MAP_H * scale;
	canvas.style.width = w + 'px';
	canvas.style.height = MAP_H * scale + 'px';
	transform = {scale, ox: 0, oy: 0};
	draw();
}

function getRegionAt(mx, my) {
	const {scale, ox, oy} = transform;
	for (let i = 0; i < REGIONS.length; i++) {
		const {pts} = REGIONS[i];
		if (pts.length < 3) continue;
		let inside = false;
		for (let j = 0, k = pts.length - 1; j < pts.length; k = j++) {
		const xi = pts[j].x * scale + ox;
		const yi = pts[j].y * scale + oy;
		const xk = pts[k].x * scale + ox;
		const yk = pts[k].y * scale + oy;
		const crosses = (yi > my) !== (yk > my) &&
						mx < ((xk - xi) * (my - yi)) / (yk - yi) + xi;
		if (crosses) inside = !inside;
		}
		if (inside) return i;
	}
	return -1;
}

