const allPoints = REGIONS.flatMap(r => r.pts);
const MIN_X = Math.min(...allPoints.map(p => p.x));
const MIN_Y = Math.min(...allPoints.map(p => p.y));
const MAX_X = Math.max(...allPoints.map(p => p.x));
const MAX_Y = Math.max(...allPoints.map(p => p.y));
const CONTENT_W = MAX_X - MIN_X;
const CONTENT_H = MAX_Y - MIN_Y;

const canvas = document.getElementById('mapCanvas');
const ctx = canvas.getContext('2d');
const style = getComputedStyle(document.documentElement);

const COLOR_BG = style.getPropertyValue('--color-bg').trim();
const COLOR_STROKE = style.getPropertyValue('--color-stroke').trim();
const COLOR_STROKE_HOVER = style.getPropertyValue('--color-stroke-hover').trim();

const tooltip = document.getElementById('regionTooltip');

let hoverIndex = -1;
let transform  = { scale: 1, ox: 0, oy: 0 };

const PADDING = 100;


function draw() {
    const { scale, ox, oy } = transform;

    ctx.clearRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = COLOR_BG;
    ctx.fillRect(0, 0, canvas.width, canvas.height);

    for (let i = 0; i < REGIONS.length; i++) {
        const {color, colorHover, isCapital, pts } = REGIONS[i];

        if (pts.length < 3) continue;

        ctx.beginPath();
        ctx.moveTo(pts[0].x * scale + ox, pts[0].y * scale + oy);
        for (let j = 1; j < pts.length; j++) {
            ctx.lineTo(pts[j].x * scale + ox, pts[j].y * scale + oy);
        }
        ctx.closePath();

        const isHovered = i === hoverIndex;
        ctx.globalAlpha = isCapital ? 1.0 : 0.5;
        ctx.fillStyle   = isHovered ? (colorHover) : (color);
        ctx.strokeStyle = isHovered ? COLOR_STROKE_HOVER : COLOR_STROKE;
        ctx.lineWidth   = isHovered ? 2 : 0.8;
        ctx.fill();
        ctx.stroke();
    }
}


function resize() {
    const containerW = canvas.parentElement.clientWidth;
    const availableW = containerW - PADDING * 2;
    const scale = availableW / CONTENT_W;

    const drawW = CONTENT_W * scale + PADDING * 2;
    const drawH = CONTENT_H * scale + PADDING * 2;

    canvas.width  = drawW;
    canvas.height = drawH;
    canvas.style.width  = drawW + 'px';
    canvas.style.height = drawH + 'px';
    transform = {
        scale,
        ox: -MIN_X * scale + PADDING,
        oy: -MIN_Y * scale + PADDING,
    };
    draw();
}


function getRegionAt(mx, my) {
    const { scale, ox, oy } = transform;

    for (let i = 0; i < REGIONS.length; i++) {
        const { pts } = REGIONS[i];
        if (pts.length < 3) continue;

        let inside = false;
        for (let j = 0, k = pts.length - 1; j < pts.length; k = j++) {
            const xi = pts[j].x * scale + ox;
            const yi = pts[j].y * scale + oy;
            const xk = pts[k].x * scale + ox;
            const yk = pts[k].y * scale + oy;
            const crosses = (yi > my) !== (yk > my) &&
                mx < ((xk - xi) * (my - yi)) / (yk - yi) + xi;
            if (crosses) inside = !inside;
        }
        if (inside) return i;
    }
    return -1;
}


canvas.addEventListener('mousemove', e => {
    const rect   = canvas.getBoundingClientRect();
    const scaleX = canvas.width  / rect.width;
    const scaleY = canvas.height / rect.height;
    const mx = (e.clientX - rect.left) * scaleX;
    const my = (e.clientY - rect.top)  * scaleY;
 
    const idx = getRegionAt(mx, my);
    if (idx !== hoverIndex) {
        hoverIndex = idx;
        canvas.style.cursor = idx !== -1 ? 'pointer' : 'default';
        draw();
    }
    
    if (idx !== -1) {
        const region = REGIONS[idx];
        tooltip.innerHTML = `
            <span class="tooltip-name">${region.name}</span>
            ${region.context ? `<span class="tooltip-context">${region.context}</span>` : ''}
            ${region.status ? `<span class="tooltip-status" style="background:${region.statusColor}20; color:${region.statusColor}; border: 1px solid ${region.statusColor}60">${region.status}</span>` : ''}
        `;
        tooltip.classList.add('visible');
        tooltip.style.left = (e.clientX + 14) + 'px';
        tooltip.style.top  = (e.clientY - 10) + 'px';
    } else {
        tooltip.classList.remove('visible');
    }
});

